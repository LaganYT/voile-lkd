#!/usr/bin/env python3
"""Generate the x86-64 syscall number table for LKD from the Linux v6.12 table.

Inputs : tools/data/syscall_64.tbl.v6.12  (downloaded copy of
         https://raw.githubusercontent.com/torvalds/linux/v6.12/arch/x86/entry/syscalls/syscall_64.tbl)
Outputs: include/lkd/syscall_nr.h   LKD_NR_<name> macros, table size, source URL and sha256
         src/core/syscall_names.c   name table used by the tracer

Only the "common" and "64" ABIs are kept; the "x32" range (512 and above) is not
part of the x86-64 ABI and always returns -ENOSYS in LKD.

Usage: tools/gen_syscall_table.py [--fetch]
  --fetch  re-download the table from the URL above before generating.
"""
import hashlib
import os
import sys
import urllib.request

URL = "https://raw.githubusercontent.com/torvalds/linux/v6.12/arch/x86/entry/syscalls/syscall_64.tbl"
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TBL = os.path.join(ROOT, "tools", "data", "syscall_64.tbl.v6.12")
OUT_H = os.path.join(ROOT, "include", "lkd", "syscall_nr.h")
OUT_C = os.path.join(ROOT, "src", "core", "syscall_names.c")
TABLE_SIZE = 512  # x32 numbers start at 512 (__X32_SYSCALL_BIT)


def main():
    if "--fetch" in sys.argv:
        with urllib.request.urlopen(URL, timeout=30) as r:
            data = r.read()
        with open(TBL, "wb") as f:
            f.write(data)
    with open(TBL, "rb") as f:
        raw = f.read()
    sha = hashlib.sha256(raw).hexdigest()
    entries = {}
    for line in raw.decode().splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        parts = line.split()
        nr, abi, name = int(parts[0]), parts[1], parts[2]
        if abi not in ("common", "64"):
            continue
        if nr >= TABLE_SIZE:
            raise SystemExit("syscall %s: number %d exceeds the table size" % (name, nr))
        if nr in entries:
            raise SystemExit("duplicate syscall number %d" % nr)
        entries[nr] = name
    # restart_syscall is 219 in the table; keep every other name as is.
    last = max(entries)

    h = []
    h.append("/* GENERATED by tools/gen_syscall_table.py. Do not edit.")
    h.append(" * Source : %s" % URL)
    h.append(" * SHA-256: %s" % sha)
    h.append(" * Linux x86-64 syscall numbers (abi common and 64), %d entries, highest %d. */" % (len(entries), last))
    h.append("#ifndef LKD_SYSCALL_NR_H")
    h.append("#define LKD_SYSCALL_NR_H")
    h.append("")
    h.append("#define LKD_SYSCALL_TABLE_SOURCE_URL \"%s\"" % URL)
    h.append("#define LKD_SYSCALL_TABLE_SHA256 \"%s\"" % sha)
    h.append("/* Size of every table indexed by syscall number. Numbers >= this are -ENOSYS. */")
    h.append("#define LKD_NR_TABLE_SIZE %d" % TABLE_SIZE)
    h.append("#define LKD_NR_HIGHEST %d" % last)
    h.append("")
    for nr in sorted(entries):
        h.append("#define LKD_NR_%s %d" % (entries[nr], nr))
    h.append("")
    h.append("/* Name of syscall nr, or NULL when the number is unassigned or out of range. */")
    h.append("const char *lkd_syscall_name(unsigned long nr);")
    h.append("")
    h.append("#endif /* LKD_SYSCALL_NR_H */")
    with open(OUT_H, "w") as f:
        f.write("\n".join(h) + "\n")

    c = []
    c.append("/* GENERATED by tools/gen_syscall_table.py. Do not edit.")
    c.append(" * Source : %s" % URL)
    c.append(" * SHA-256: %s */" % sha)
    c.append("#include <lkd/syscall_nr.h>")
    c.append("")
    c.append("static const char *const names[LKD_NR_TABLE_SIZE] = {")
    for nr in sorted(entries):
        c.append("    [%d] = \"%s\"," % (nr, entries[nr]))
    c.append("};")
    c.append("")
    c.append("const char *lkd_syscall_name(unsigned long nr)")
    c.append("{")
    c.append("    return nr < LKD_NR_TABLE_SIZE ? names[nr] : (const char *)0;")
    c.append("}")
    with open(OUT_C, "w") as f:
        f.write("\n".join(c) + "\n")
    print("wrote %s and %s (%d syscalls, sha256 %s)" % (OUT_H, OUT_C, len(entries), sha))


if __name__ == "__main__":
    main()
