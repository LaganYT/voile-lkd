/*
 * d_jit_signal_state.c - fact group D (faults and signals) crossed with group C (JIT):
 * what happens to the per-thread MAP_JIT write protection when a signal is delivered.
 *
 * For every combination of
 *   state of the thread when the signal arrives: write mode (pthread_jit_write_protect_np(0)) or exec mode (1)
 *   what the handler does to the state: nothing / switches to exec / switches to write
 *   how the signal is generated: pthread_kill from the thread itself, from another thread, synchronous brk
 * the program measures
 *   - what the handler can do when it starts (store to a JIT page? call a JIT stub?)
 *   - what the thread can do after sigreturn
 * and whether a handler can redirect the resumed pc into JIT code.
 *
 * The state is observed by trying the operation under a sigsetjmp/siglongjmp guard.  Each
 * observation uses a separate run so that a probe fault never disturbs another observation.
 */
#include "cd_common.h"

#define KiB (1ULL << 10)

static uint32_t *g_jit;
static volatile int g_action;        /* 0 none, 1 -> exec, 2 -> write */
static volatile int g_entry_probe;   /* -1 none, 0 store, 1 exec */
static volatile int g_entry_sig;
static volatile uint64_t g_redirect;
static volatile int g_handler_ran;
static _Atomic int g_flag;

static void trap_handler(int sig, siginfo_t *si, void *uctx) {
  ucontext_t *uc = (ucontext_t *)uctx;
  (void)sig; (void)si;
  g_handler_ran++;
  if (g_entry_probe == 0) g_entry_sig = cd_probe_store32(&g_jit[256], 0x12345678u, NULL);
  else if (g_entry_probe == 1) g_entry_sig = cd_probe_call(&g_jit[0], NULL, NULL);
  if (g_action == 1) cd_jit_exec();
  else if (g_action == 2) cd_jit_write();
  if (g_redirect) CD_PC(uc) = g_redirect;
  else if (sig == SIGTRAP) CD_PC(uc) += 4;
  atomic_store(&g_flag, 1);
}

static void *killer(void *a) {
  pthread_t target = *(pthread_t *)a;
  usleep(2000);
  pthread_kill(target, SIGUSR1);
  return NULL;
}

static const char *sg(int s) { return s ? sig_name(s) : "ok"; }

/* how: 0 = pthread_kill(self), 1 = pthread_kill from another thread while spinning in C, 2 = brk */
static void deliver(int how) {
  atomic_store(&g_flag, 0);
  if (how == 0) pthread_kill(pthread_self(), SIGUSR1);
  else if (how == 1) {
    pthread_t self = pthread_self(), k;
    pthread_create(&k, NULL, killer, &self);
    while (!atomic_load(&g_flag)) __asm__ volatile("yield");
    pthread_join(k, NULL);
  } else {
    __asm__ volatile("brk #0");
  }
}

static const char *how_name(int how) { return how == 0 ? "pthread_kill(self)" : (how == 1 ? "pthread_kill from another thread (target spinning in C)" : "synchronous brk #0"); }

static int child_state(void *a) {
  (void)a;
  g_jit = cd_jit_map(64 * KiB, CD_RWX, 0, NULL);
  if (!g_jit) { INFO("J00.setup", "MAP_JIT unavailable: %s", errno_name(errno)); return 0; }
  cd_install_probe_handlers();
  struct sigaction sa;
  memset(&sa, 0, sizeof sa);
  sa.sa_sigaction = trap_handler;
  sa.sa_flags = SA_SIGINFO | SA_NODEFER;
  sigemptyset(&sa.sa_mask);
  sigaction(SIGUSR1, &sa, NULL);
  sigaction(SIGTRAP, &sa, NULL);
  cd_jit_write();
  cd_emit_ret_const(&g_jit[0], 42);
  cd_jit_exec();
  sys_icache_invalidate(g_jit, 8);

  for (int how = 0; how < 3; how++) {
    INFO("J01.header", "---- signal generated by: %s", how_name(how));
    /* entry state */
    for (int pre = 0; pre < 2; pre++) {
      int res[2];
      for (int probe = 0; probe < 2; probe++) {
        g_action = 0;
        g_redirect = 0;
        g_entry_probe = probe;
        g_entry_sig = -1;
        g_handler_ran = 0;
        if (pre) cd_jit_write(); else cd_jit_exec();
        deliver(how);
        cd_jit_exec();
        res[probe] = g_entry_sig;
      }
      INFO("J01.entry", "thread in %s when the signal arrives: inside the handler at entry, store to a JIT page = %s, call into a JIT page = %s",
           pre ? "WRITE mode" : "EXEC mode", sg(res[0]), sg(res[1]));
    }
    /* state after sigreturn */
    for (int pre = 0; pre < 2; pre++) {
      for (int action = 0; action < 3; action++) {
        int after[2];
        for (int probe = 0; probe < 2; probe++) {
          g_action = action;
          g_redirect = 0;
          g_entry_probe = -1;
          if (pre) cd_jit_write(); else cd_jit_exec();
          deliver(how);
          int sig;
          if (probe == 0) sig = cd_probe_store32(&g_jit[256], 0x12345678u, NULL);
          else sig = cd_probe_call(&g_jit[0], NULL, NULL);
          cd_jit_exec();
          after[probe] = sig;
        }
        const char *state = (after[0] == 0 && after[1] != 0) ? "WRITE mode" : ((after[0] != 0 && after[1] == 0) ? "EXEC mode" : "UNEXPECTED combination");
        INFO("J01.after", "thread in %s on arrival, handler %s: after sigreturn the thread is in %s (store=%s, call=%s)",
             pre ? "WRITE mode" : "EXEC mode", action == 0 ? "changes nothing" : (action == 1 ? "calls pthread_jit_write_protect_np(1)" : "calls pthread_jit_write_protect_np(0)"),
             state, sg(after[0]), sg(after[1]));
      }
    }
  }
  return 0;
}

/* sigreturn into JIT code */
__asm__(
    ".text\n"
    ".p2align 4\n"
    ".globl _cd_trap_call\n"
    "_cd_trap_call:\n"
    "  brk #0\n"
    "  ret\n");
extern uint64_t cd_trap_call(void);

static int child_redirect(void *a) {
  (void)a;
  g_jit = cd_jit_map(64 * KiB, CD_RWX, 0, NULL);
  if (!g_jit) { INFO("J02.setup", "MAP_JIT unavailable"); return 0; }
  cd_install_probe_handlers();
  struct sigaction sa;
  memset(&sa, 0, sizeof sa);
  sa.sa_sigaction = trap_handler;
  sa.sa_flags = SA_SIGINFO | SA_NODEFER;
  sigemptyset(&sa.sa_mask);
  sigaction(SIGTRAP, &sa, NULL);
  cd_jit_write();
  cd_emit_ret_const(&g_jit[0], 42);
  cd_jit_exec();
  sys_icache_invalidate(g_jit, 8);
  for (int pre = 0; pre < 2; pre++) {
    for (int action = 0; action < 3; action++) {
      g_action = action;
      g_entry_probe = -1;
      g_redirect = (uint64_t)(uintptr_t)&g_jit[0];
      if (pre) cd_jit_write(); else cd_jit_exec();
      uint64_t out = 0;
      int sig = cd_probe_call((void *)cd_trap_call, &out, NULL);
      cd_jit_exec();
      INFO("J02.redirect", "thread in %s at the brk, handler %s and sets pc to a JIT stub (movz x0,#42; ret): the resumed thread %s",
           pre ? "WRITE mode" : "EXEC mode",
           action == 0 ? "changes nothing" : (action == 1 ? "calls pthread_jit_write_protect_np(1)" : "calls pthread_jit_write_protect_np(0)"),
           sig ? (sig == SIGBUS ? "faults with SIGBUS (cannot execute the JIT page)" : "faults with another signal") : (out == 42 ? "runs the stub and returns 42" : "returned something else"));
    }
  }
  return 0;
}

/* synchronous fault raised by JIT code itself, state at entry and after */
__asm__(
    ".text\n"
    ".p2align 4\n"
    ".globl _cd_host_ret\n"
    "_cd_host_ret:\n"
    "  ret\n");
extern void cd_host_ret(void);

static void fault_handler(int sig, siginfo_t *si, void *uctx) {
  ucontext_t *uc = (ucontext_t *)uctx;
  (void)si;
  g_handler_ran++;
  if (g_entry_probe == 0) g_entry_sig = cd_probe_store32(&g_jit[512], 1, NULL);
  else if (g_entry_probe == 1) g_entry_sig = cd_probe_call(&g_jit[0], NULL, NULL);
  if (g_action == 1) cd_jit_exec(); else if (g_action == 2) cd_jit_write();
  /* leave the JIT page: resume in host code that returns to the caller of the JIT function */
  CD_PC(uc) = (uint64_t)(uintptr_t)&cd_host_ret;
  (void)sig;
}

static int child_jitfault(void *a) {
  (void)a;
  g_jit = cd_jit_map(64 * KiB, CD_RWX, 0, NULL);
  if (!g_jit) { INFO("J03.setup", "MAP_JIT unavailable"); return 0; }
  cd_install_probe_handlers();
  struct sigaction sa;
  memset(&sa, 0, sizeof sa);
  sa.sa_sigaction = fault_handler;
  sa.sa_flags = SA_SIGINFO | SA_NODEFER;
  sigemptyset(&sa.sa_mask);
  sigaction(SIGSEGV, &sa, NULL);
  void *hole = mmap(NULL, 16 * KiB, PROT_READ | PROT_WRITE, MAP_PRIVATE | MAP_ANON, -1, 0);
  munmap(hole, 16 * KiB);
  cd_jit_write();
  cd_emit_ret_const(&g_jit[0], 42);
  g_jit[128] = A64_LDR_X(1, 0);   /* faults on the unmapped address in x0 */
  g_jit[129] = A64_RET;
  cd_jit_exec();
  sys_icache_invalidate(g_jit, 4096);
  for (int probe = 0; probe < 2; probe++) {
    g_action = 0;
    g_entry_probe = probe;
    g_entry_sig = -1;
    g_handler_ran = 0;
    cd_jit_exec();
    ((uint64_t(*)(uint64_t))&g_jit[128])((uint64_t)(uintptr_t)hole);
    INFO("J03.jit-fault", "load fault raised by code running in the JIT page (thread in EXEC mode, SIGSEGV): handler ran %d time(s); at handler entry %s = %s", g_handler_ran,
         probe == 0 ? "store to a JIT page" : "call into a JIT page", sg(g_entry_sig));
  }
  for (int action = 0; action < 3; action++) {
    g_action = action;
    g_entry_probe = -1;
    cd_jit_exec();
    ((uint64_t(*)(uint64_t))&g_jit[128])((uint64_t)(uintptr_t)hole);
    int s0 = cd_probe_store32(&g_jit[512], 1, NULL);
    cd_jit_exec();
    INFO("J03.jit-fault", "after that fault, handler %s and resumes in host code: store to a JIT page = %s => thread is in %s",
         action == 0 ? "changes nothing" : (action == 1 ? "sets exec mode" : "sets write mode"), sg(s0), s0 == 0 ? "WRITE mode" : "EXEC mode");
  }
  return 0;
}

int main(int argc, char **argv) {
  dm_arm_watchdog(200);
  setvbuf(stdout, NULL, _IOLBF, 0);
  const char *only = argc > 1 ? argv[1] : NULL;
  cd_print_header(argv[0]);
  static const struct { const char *tag; cd_child_fn fn; } tests[] = {{"J01", child_state}, {"J02", child_redirect}, {"J03", child_jitfault}};
  for (size_t i = 0; i < sizeof tests / sizeof tests[0]; i++) {
    if (only && !strstr(only, tests[i].tag)) continue;
    int to = 0;
    char sb[96];
    int st = cd_run_child(tests[i].fn, NULL, 60000, &to);
    INFO(tests[i].tag, "child result: %s", cd_status_str(st, to, sb, sizeof sb));
  }
  printf("SUMMARY pass=%d fail=%d info=%d\n", g_pass, g_fail, g_info);
  return 0;
}
